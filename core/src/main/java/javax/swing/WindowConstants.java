package javax.swing;

/**
 * Swing {@code WindowConstants}: the default-close-operation constants that
 * {@code Window.setDefaultCloseOperation} interprets.
 */
public interface WindowConstants {
    int DO_NOTHING_ON_CLOSE = 0;
    int HIDE_ON_CLOSE = 1;
    int DISPOSE_ON_CLOSE = 2;
    int EXIT_ON_CLOSE = 3;
}
